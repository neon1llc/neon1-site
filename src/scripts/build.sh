#!/usr/bin/env bash
# neon1-site :: scripts/build.sh
# Purpose: Build or copy the static site into dist/ (used by GitHub Actions CI/CD).
# Notes: Works for both Node-based builds (React/Vue/etc) and plain static HTML.

set -euo pipefail   # Exit on error, undefined vars, or pipe failures

# -------------------------------------------------------------------
# Define key directories
# -------------------------------------------------------------------
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"  # repo root
APP_DIR="$ROOT_DIR/app"                                      # where the site source lives
DIST_DIR="$ROOT_DIR/dist"                                    # output folder (synced to S3)

# Clean and recreate dist/
rm -rf "$DIST_DIR"
mkdir -p "$DIST_DIR"

# -------------------------------------------------------------------
# Build logic
# -------------------------------------------------------------------
if [ -f "$APP_DIR/package.json" ]; then
    # Case 1: Node.js project detected
    echo "[build] Node project detected → running npm ci && npm run build"

    cd "$APP_DIR"
    npm ci                       # clean, reproducible install
    npm run build                # run project’s build script

    # Copy build artifacts into dist/
    if [ -d "dist" ]; then
        cp -R dist/* "$DIST_DIR/"
    elif [ -d "build" ]; then
        cp -R build/* "$DIST_DIR/"
    else
        echo "[build] Build completed, but no dist/ or build/ folder found."
        echo "[build] Falling back to copying public/ and src/."
        [ -d "public" ] && cp -R public/* "$DIST_DIR/" || true
        [ -d "src" ] && cp -R src/* "$DIST_DIR/" || true
    fi
else
    # Case 2: Plain static assets (no Node.js build step)
    echo "[build] No package.json found → copying app/public and app/src directly"
    [ -d "$APP_DIR/public" ] && cp -R "$APP_DIR/public/"* "$DIST_DIR/" || true
    [ -d "$APP_DIR/src" ] && cp -R "$APP_DIR/src/"* "$DIST_DIR/" || true
fi

# -------------------------------------------------------------------
# Neo config placeholder
# -------------------------------------------------------------------
# This file will be overwritten by CI/CD after Terraform apply
# with the actual API Gateway URL for the Neo chat backend.
echo "window.NEO_CHAT_API='';" > "$DIST_DIR/neo-config.js"

# -------------------------------------------------------------------
# Safety: ensure index.html always exists
# -------------------------------------------------------------------
if [ ! -f "$DIST_DIR/index.html" ]; then
    cat > "$DIST_DIR/index.html" <<'EOF'
<!doctype html>
<html>
  <head><meta charset="utf-8"><title>neon1-site</title></head>
  <body><h1>neon1-site</h1><p>Default index.html (generated by build.sh)</p></body>
</html>
EOF
fi

# -------------------------------------------------------------------
# Done
# -------------------------------------------------------------------
echo "[build] dist/ is ready at $DIST_DIR"
