// scripts/page-shell.mjs - Everything the generated pages (the Knowledge Center and the blog) share: the page itself
// (head, bar, menu, footer, and scripts), the parts of a document page, structured data, and writing or checking a
// generated folder. The bar, menu, and footer come from index.html, so a generated page always matches the home page.

import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, statSync, existsSync } from "node:fs"
import { join, dirname, relative } from "node:path"
import { esc, longDate, SITE, CORPUS_BLOB } from "./knowledge-lib.mjs"


// Everything a page needs from index.html: its release number, its frame blocks, and its bar and menu links.
// The links are read from the home page, not listed here, so every page's menu says exactly what the home
// page's says, in the same order, on desktop and on phones
export function homeFrame(home) {
  const version = home.match(/<meta name="version" content="([^"]+)"/)[1]
  const block = (name) => {
    const m = home.match(new RegExp(`<!-- frame:${name} -->[\\s\\S]*?<!-- /frame:${name} -->`))
    if (!m) throw new Error(`index.html has no frame:${name} block`)
    return m[0]
  }
  // The bar's links before the shared actions, and every link in the phone menu
  const bar = home.match(/<ul class="links">\n([\s\S]*?)\n\s*<!-- frame:actions -->/)
  const menu = home.match(/<div class="menu" id="menu" hidden>\s*<ul>\n([\s\S]*?)\n\s*<\/ul>/)
  if (!bar || !menu) throw new Error("index.html has no bar links or menu list")
  return { version, block, barLinks: toHome(bar[1]), menuLinks: toHome(menu[1]) }
}

// A link to a part of the home page ("#services") reaches it from another page by full path ("/#services")
const toHome = (html) => html.replace(/href="#/g, 'href="/#')

// Structured data as one graph. "<" is escaped so no text can close the script element early
export const jsonLd = (graph) => JSON.stringify({ "@context": "https://schema.org", "@graph": graph }).replace(/</g, "\\u003c")


// One page. current names the area whose bar link is marked as the current page; generator names the script
// and make target that wrote it, for the comment at the top; head adds lines to <head>, such as a feed link
export function page(frame, { title, description, path, main, kind, ld, current, generator, styles = [], scripts = [], head = "" }) {
  const url = SITE + path
  // The bar marks the current area (knowledge or blog) as the page the reader is on
  const navLinks = frame.barLinks.replace(/<a href="(\/[^"#]+\/)">([^<]+)<\/a>/g,
    (link, href, label) => label === current ? `<a href="${href}" aria-current="page">${label}</a>` : link)
  return `<!doctype html>
<!-- ${path}index.html - Generated by ${generator}. -->
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
  <meta name="version" content="${frame.version}" />
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}" />
  <meta name="theme-color" content="#F2F4F2" />
  <link rel="canonical" href="${url}" />
  <meta property="og:type" content="${kind === "doc" ? "article" : "website"}" />
  <meta property="og:site_name" content="neon1" />
  <meta property="og:title" content="${esc(title)}" />
  <meta property="og:description" content="${esc(description)}" />
  <meta property="og:url" content="${url}" />
  <meta property="og:image" content="${OG_IMAGE}" />
  <meta name="twitter:card" content="summary_large_image" />${ld ? `
  <!-- What this page is, for search engines and AI answers: built from the same corpus fields the page shows -->
  <script type="application/ld+json">${jsonLd(ld)}</script>` : ""}${head}
  ${frame.block("icons")}
  <link rel="stylesheet" href="/shared/neon1.css" />
  <link rel="stylesheet" href="/css/frame.css" />
${styles.map((s) => `  <link rel="stylesheet" href="${s}" />`).join("\n")}
</head>
<body class="kc">
  <a class="skip" href="#main">skip to content</a>

  <header class="n1-bar light">
    <nav class="n1-inner" aria-label="Main">
      ${frame.block("logo")}
      <ul class="links">
${navLinks}
        ${frame.block("actions")}
      </ul>
      ${frame.block("menu-button")}
    </nav>
  </header>

  <div class="menu" id="menu" hidden>
    <ul>
${frame.menuLinks}
    </ul>
  </div>

  <div class="top awake kc-page">
  <main id="main">
${main}
  </main>

  ${frame.block("footer")}
  </div>

  <script type="module" src="/js/frame.js"></script>
${scripts.map((s) => `  <script type="module" src="${s}"></script>`).join("\n")}
</body>
</html>
`
}


