// A document as a small card: title, summary, and whether it has a PDF. The shelf heading already
// names the kind, so the card doesn't repeat it
function card(d) {
  const tags = d.pdf ? ["PDF"] : []
  // Search reads the title, summary, type, audience, and every section heading
  const headings = d.sections.map((x) => x.heading).filter(Boolean)
  const words = [d.title, d.summary, TYPE_LABELS[d.type], d.data.audience, corpus.manifest.shelves[d.section].label, ...headings]
    .filter(Boolean).join(" ").replace(/[*_`]/g, "").toLowerCase()
  return `        <li class="kc-card" data-words="${esc(words)}">
          <a href="${d.url}">
            <span class="kc-card-title">${esc(d.title)}</span>
            <span class="kc-card-summary">${esc(d.summary)}</span>
            ${tags.length ? `<span class="kc-tags">${tags.map((t) => `<span>${esc(t)}</span>`).join("")}</span>` : ""}
          </a>
        </li>`
}


// The front door: what this is, a search box, then the two groups and their shelves. Featured documents
// lead their shelf, and documents for developers sit in a closed fold at its end
const DEVELOPERS = "Developers"
const cardList = (docs) => `<ul class="kc-cards">
${docs.map(card).join("\n")}
        </ul>`
function shelfSection(s) {
  const lead = s.docs.filter((d) => d.data.featured)
  const rest = s.docs.filter((d) => !d.data.featured && d.data.audience !== DEVELOPERS)
  const dev = s.docs.filter((d) => !d.data.featured && d.data.audience === DEVELOPERS)
  const fold = dev.length
    ? `
        <details class="kc-fold">
          <summary>For developers <span>${dev.length}</span></summary>
          ${cardList(dev)}
        </details>`
    : ""
  return `      <section class="kc-shelf" id="${s.key}" aria-labelledby="${s.key}-h">
        <div class="kc-shelf-head">
          <h3 id="${s.key}-h">${esc(s.label)}</h3>
          <p>${esc(s.description)}</p>
        </div>
        ${cardList([...lead, ...rest])}${fold}
      </section>`
}

function indexPage() {
  const count = corpus.docs.length
  const pdfs = corpus.docs.filter((d) => d.pdf).length
  const groups = corpus.groups
    .map((g) => `    <section class="kc-group" id="${g.key}" aria-labelledby="${g.key}-h">
      <div class="kc-group-head">
        <h2 id="${g.key}-h">${esc(g.label)}</h2>
        <p>${esc(g.description)}</p>
      </div>
${g.shelves.map(shelfSection).join("\n\n")}
    </section>`)
    .join("\n\n")
  const nav = corpus.groups
    .map((g) => `        <li class="kc-nav-group"><span>${esc(g.label)}</span></li>
${g.shelves.map((s) => `        <li><a href="#${s.key}">${esc(s.label)} <span>${s.docs.length}</span></a></li>`).join("\n")}`)
    .join("\n")
  const main = `    <section class="kc-band" aria-labelledby="kc-title">
      <div class="kc-band-inner">
        <p class="kc-eyebrow">neon1 · knowledge center</p>
        <h1 id="kc-title">Everything neon1</h1>
        <p class="kc-lead">Guides, templates, forms, and filled-out examples, plus how I work, services, and policies. ${count} documents, ${pdfs} with a PDF to download.</p>
        <div class="kc-search" hidden>
          <label for="kc-q">Search the knowledge center</label>
          <input id="kc-q" type="search" placeholder="Try &quot;backup&quot;, &quot;proposal&quot;, or &quot;privacy&quot;" autocomplete="off" />
          <p class="kc-results" id="kc-results" role="status"></p>
        </div>
      </div>
    </section>

    <nav class="kc-shelves" aria-label="Shelves">
      <ul>
${nav}
      </ul>
    </nav>

    <div class="kc-body">
${groups}

    <p class="kc-colophon">These documents come from <a class="ext" href="https://github.com/neon1llc/neon1-corpus" target="_blank" rel="noopener">neon1-corpus</a> and are shared under CC BY-ND 4.0. Templates and examples are illustrations, not legal advice.</p>
    </div>`
  return page({
    title: "Knowledge center · neon1",
    description: "neon1's public documents in one place: guides, templates, forms, filled-out examples, and alternatives, plus standards, services, and policies, each with a PDF to download.",
    path: BASE,
    main,
    kind: "index",
  })
}


// One document: where it sits, its title and facts, the PDF, the text, and where to go next
function docPage(d) {
  const shelf = corpus.manifest.shelves[d.section]
  const facts = [
    ["Type", TYPE_LABELS[d.type] ?? d.type],
    d.data.edition ? ["Edition", d.data.edition] : null,
    d.data.created && d.data.created !== d.data.updated ? ["First written", longDate(d.data.created)] : null,
    ["Updated", longDate(d.data.updated)],
    d.data.reviewed ? ["Facts checked", longDate(d.data.reviewed)] : null,
    d.data.audience ? ["For", d.data.audience] : null,
  ].filter(Boolean)

  const pairs = []
  if (d.data.example_of && corpus.byId.has(d.data.example_of)) pairs.push(["The blank version", corpus.byId.get(d.data.example_of)])
  for (const ex of corpus.docs.filter((x) => x.data.example_of === d.id)) pairs.push(["See it filled in", ex])
  const related = (d.data.related ?? []).map((id) => corpus.byId.get(id)).filter((r) => r && !pairs.some(([, p]) => p.id === r.id))

  const next = [
    ...pairs.map(([label, p]) => `          <li class="kc-pair"><a href="${p.url}"><span class="kc-kicker">${label}</span><span class="kc-card-title">${esc(p.title)}</span></a></li>`),
    ...related.map((r) => `          <li><a href="${r.url}"><span class="kc-kicker">${esc(corpus.manifest.shelves[r.section].label)}</span><span class="kc-card-title">${esc(r.title)}</span></a></li>`),
  ]

  const body = relink(d.html, d, corpus)
    .replace(/<a href="(https?:[^"]+)">/g, '<a class="ext" href="$1" target="_blank" rel="noopener">')
  const fictional = d.data.fictional ? '<p class="kc-flag">Fictional example</p>' : ""

  const main = `    <article class="kc-doc">
      <header class="kc-doc-head">
        <nav class="kc-crumbs" aria-label="Breadcrumb"><a href="${BASE}">Knowledge center</a><span aria-hidden="true">/</span><a href="${BASE}#${d.section}">${esc(shelf.label)}</a></nav>
        ${fictional}<h1>${esc(d.title)}</h1>
        <p class="kc-summary">${esc(d.summary)}</p>
        <dl class="kc-facts">
${facts.map(([k, v]) => `          <div><dt>${esc(k)}</dt><dd>${esc(v)}</dd></div>`).join("\n")}
        </dl>
        <div class="kc-actions">
          ${d.pdf ? `<a class="btn btn-primary" href="${d.pdf}" download>${ICON_PDF}Download PDF</a>` : ""}
        </div>
      </header>

      <div class="kc-text">
${body}
      </div>
${next.length ? `
      <aside class="kc-next" aria-labelledby="kc-next-h">
        <h2 id="kc-next-h">Read next</h2>
        <ul>
${next.join("\n")}
        </ul>
      </aside>` : ""}

      <p class="kc-colophon">© neon1 LLC (neon1.tech). Shared under CC BY-ND 4.0: copy and share it word for word with credit. <a class="ext" href="${esc(`https://github.com/neon1llc/neon1-corpus/blob/main/${d.source}`)}" target="_blank" rel="noopener">Source on GitHub</a>. ${d.type === "template" || d.type === "example" ? "Templates and examples are illustrations, not legal advice." : ""}</p>
    </article>`
  return page({ title: `${d.title} · neon1 knowledge center`, description: d.summary, path: d.url, main, kind: "doc" })
}


// Everything the folder should hold, by path under the site
const want = new Map([["knowledge/index.html", indexPage()]])
for (const d of corpus.docs) want.set(`${d.url.slice(1)}index.html`, docPage(d))

// The sitemap lists every knowledge center page between its <!-- knowledge --> markers, with each document's updated date
const sitemapFile = join(siteDir, "sitemap.xml")
const sitemapNow = readFileSync(sitemapFile, "utf8")
const lastmod = corpus.docs.map((d) => d.data.updated).sort().at(-1)
const urls = [`  <url><loc>${SITE}${BASE}</loc><lastmod>${lastmod}</lastmod></url>`,
  ...corpus.docs.map((d) => `  <url><loc>${SITE}${d.url}</loc><lastmod>${d.data.updated}</lastmod></url>`)]
const sitemapWant = sitemapNow.replace(/  <!-- knowledge -->[\s\S]*?<!-- \/knowledge -->/, `  <!-- knowledge -->\n${urls.join("\n")}\n  <!-- /knowledge -->`)
if (!sitemapNow.includes("<!-- knowledge -->")) throw new Error("sitemap.xml has no <!-- knowledge --> block")

// What the folder holds now, PDFs left out since the deploy job writes those
const walk = (dir) => (existsSync(dir) ? readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)])) : [])
const have = walk(join(siteDir, "knowledge")).map((f) => relative(siteDir, f)).filter((f) => !f.endsWith(".pdf"))

// Each page stays light: the text of one document plus the shared frame
const PAGE_MAX = 120 * 1024
for (const [path, html] of want) if (Buffer.byteLength(html) > PAGE_MAX) {
  console.error(`knowledge: ${path} is ${Math.round(Buffer.byteLength(html) / 1024)} KB, over ${PAGE_MAX / 1024} KB`)
  process.exit(1)
}

if (mode === "check") {
  const problems = []
  for (const [path, html] of want) {
    const file = join(siteDir, path)
    if (!existsSync(file)) problems.push(`missing ${path}`)
    else if (readFileSync(file, "utf8") !== html) problems.push(`differs ${path}`)
  }
  for (const path of have) if (!want.has(path)) problems.push(`not from the corpus ${path}`)
  if (sitemapNow !== sitemapWant) problems.push("differs sitemap.xml knowledge block")
  if (problems.length) {
    console.error(problems.join("\n") + "\nknowledge: run make knowledge to rewrite the knowledge center from the pinned corpus")
    process.exit(1)
  }
  console.log(`knowledge: ${want.size} pages match the corpus`)
} else {
  for (const path of have) if (!want.has(path)) rmSync(join(siteDir, path))
  for (const [path, html] of want) {
    const file = join(siteDir, path)
    mkdirSync(dirname(file), { recursive: true })
    if (!existsSync(file) || readFileSync(file, "utf8") !== html) writeFileSync(file, html)
  }
  if (sitemapNow !== sitemapWant) writeFileSync(sitemapFile, sitemapWant)
  // Folders left empty by a removed document go too
  const prune = (dir) => {
    for (const f of readdirSync(dir)) if (statSync(join(dir, f)).isDirectory()) prune(join(dir, f))
    if (dir !== join(siteDir, "knowledge") && !readdirSync(dir).length) rmSync(dir, { recursive: true })
  }
  prune(join(siteDir, "knowledge"))
  console.log(`knowledge: wrote ${want.size} pages`)
}
