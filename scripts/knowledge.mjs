#!/usr/bin/env node
// scripts/knowledge.mjs - Writes the Knowledge Center (/knowledge/) from neon1-corpus, or checks it matches.
// Usage: node scripts/knowledge.mjs sync|check SITE_DIR CORPUS_EXPORT   (make knowledge, and make knowledge-check)
//
// CORPUS_EXPORT is the corpus's knowledge bundle (tools/export.mjs --target knowledge) from the tag pinned in the
// Makefile. Every document becomes /knowledge/<shelf>/<slug>/index.html, and the shelves and search live at
// /knowledge/index.html. The pages are committed, like the case studies in index.html, so a deploy stays a copy
// of the folder. The bar and footer come from index.html's frame blocks, so they match every other page. sync
// rewrites the folder; check fails if anything differs, so a hand edit or an unpulled corpus change is caught.
// PDFs are not written here: scripts/knowledge-pdf.mjs prints them in the deploy job.

import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, statSync, existsSync } from "node:fs"
import { join, dirname, relative } from "node:path"
import { load, relink, esc, longDate, TYPE_LABELS, SITE, BASE } from "./knowledge-lib.mjs"


const [mode, siteDir, exportDir] = process.argv.slice(2)
if (!["sync", "check"].includes(mode) || !siteDir || !exportDir) {
  console.error("usage: node scripts/knowledge.mjs sync|check SITE_DIR CORPUS_EXPORT")
  process.exit(2)
}

const corpus = load(exportDir)
const home = readFileSync(join(siteDir, "index.html"), "utf8")
const version = home.match(/<meta name="version" content="([^"]+)"/)[1]
const block = (name) => {
  const m = home.match(new RegExp(`<!-- frame:${name} -->[\\s\\S]*?<!-- /frame:${name} -->`))
  if (!m) throw new Error(`index.html has no frame:${name} block`)
  return m[0]
}

// The home page's sections, reached from here by full path
const SECTIONS = [["services", "services"], ["process", "process"], ["projects", "case studies"], ["work", "projects"], ["why", "about"]]
const navLinks = SECTIONS.map(([id, label]) => `        <li><a href="/#${id}">${label}</a></li>`).join("\n")
const menuLinks = [...SECTIONS, ["faq", "questions"], ["contact", "contact"]]
  .map(([id, label]) => `      <li><a href="/#${id}">${label}</a></li>`).join("\n")

const ICON_PDF = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M12 4v11m0 0-4.5-4.5M12 15l4.5-4.5M5 19h14"/></svg>'


